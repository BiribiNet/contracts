/**
 * Tops up the frontend's errors-only bundle (`frontend/lib/abi/merged-errors.json`) from the compiled
 * artifacts, and — ONLY on explicit request for an Arbitrum Sepolia redeploy — rewrites the frozen
 * Sepolia SideBet snapshot (`frontend/lib/abi/side-bet.ts`).
 *
 * WHY side-bet.ts IS PROTECTED: in the frontend that file is the frozen Arbitrum Sepolia snapshot, served
 * to testnet builds by `lib/abi/protocol.ts` (the frontend AGENTS.md forbids editing it). Mainnet builds
 * use `frontend/lib/abi/mainnet-generated.ts`, generated from this repo's `deployments/arbitrum-one-abi.json`
 * by `frontend/scripts/generate-mainnet-abi.mjs`. Overwriting the snapshot with the current SideBet build
 * already caused a regression (BiribiNet/frontend#858). The script therefore refuses to write it unless
 * `--sepolia-snapshot` is passed, which is reserved for an actual Sepolia SideBet redeploy.
 *
 * merged-errors.json is chain-agnostic (errors only, decoded by `lib/contract-errors.ts` for both chains):
 * it is updated by default, append-only (existing entries belong to other contracts and stay untouched),
 * deduplicated by error signature, from SideBet, RouletteEngine, BankVault4626 and the linked libraries
 * that revert with their own errors (mask bets: RouletteMaskBetLib, RouletteLiabilityMathLib).
 *
 * Usage (from the contracts repo root):
 *   yarn update:frontend:abis                       # merged-errors.json only
 *   yarn update:frontend:abis --check               # fail if merged-errors.json is missing an error
 *   yarn update:frontend:abis --sepolia-snapshot    # ALSO rewrite side-bet.ts (Sepolia redeploy only)
 *
 * Env:
 *   FRONTEND_DIR — override frontend folder (default: ../frontend)
 *   SKIP_COMPILE — skip `yarn hardhat compile`
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { spawnSync } from "child_process";

/** Artifacts whose custom errors can surface in a frontend revert (path relative to artifacts/contracts). */
export const ERROR_SOURCES = [
  "SideBet.sol/SideBet.json",
  "RouletteEngine.sol/RouletteEngine.json",
  "BankVault4626.sol/BankVault4626.json",
  "libraries/RouletteMaskBetLib.sol/RouletteMaskBetLib.json",
  "libraries/RouletteLiabilityMathLib.sol/RouletteLiabilityMathLib.json",
];

export const SIDE_BET_REFUSAL =
  "side-bet.ts is the frozen Arbitrum Sepolia snapshot and is not regenerated by default. " +
  "For mainnet, export deployments/arbitrum-one-abi.json here, then run frontend/scripts/generate-mainnet-abi.mjs " +
  "(it writes lib/abi/mainnet-generated.ts). Pass --sepolia-snapshot only after a Sepolia SideBet redeploy.";

const HEADER = `// lib/abi/side-bet.ts
// SideBet (Side bets) ABI — frozen Arbitrum Sepolia snapshot of the compiled artifact
// (contracts/SideBet.sol), served to testnet builds by lib/abi/protocol.ts. Mainnet uses
// lib/abi/mainnet-generated.ts (scripts/generate-mainnet-abi.mjs), never this file.
//
// Rewritten only by \`yarn update:frontend:abis --sepolia-snapshot\` in the contracts repo, after an
// actual Sepolia SideBet redeploy — do not hand-edit.

export const sideBetAbi = `;

const signature = (fragment) => `${fragment.name}(${(fragment.inputs ?? []).map((input) => input.type).join(",")})`;

function readAbi(file) {
  if (!fs.existsSync(file)) throw new Error(`missing artifact: ${file} — run \`yarn compile\`.`);
  const { abi } = JSON.parse(fs.readFileSync(file, "utf8"));
  if (!Array.isArray(abi)) throw new Error(`artifact has no abi array: ${file}`);
  return abi;
}

/**
 * Pure file update, no compilation. Returns what changed; writes nothing when `checkOnly`.
 * @param {{ repoRoot: string, frontendDir: string, sepoliaSnapshot?: boolean, checkOnly?: boolean, log?: (line: string) => void }} options
 */
export function updateFrontendAbis({ repoRoot, frontendDir, sepoliaSnapshot = false, checkOnly = false, log = console.log }) {
  const artifactsDir = path.join(repoRoot, "artifacts", "contracts");
  const sideBetAbiFile = path.join(frontendDir, "lib", "abi", "side-bet.ts");
  const mergedErrorsFile = path.join(frontendDir, "lib", "abi", "merged-errors.json");
  const result = { sideBetWritten: false, sideBetStale: false, addedErrors: [] };

  // ── side-bet.ts (frozen Sepolia snapshot) ──────────────────────────────────────
  if (sepoliaSnapshot) {
    if (!fs.existsSync(sideBetAbiFile)) throw new Error(`missing frontend file: ${sideBetAbiFile}`);
    const abi = readAbi(path.join(artifactsDir, ERROR_SOURCES[0]));
    const next = `${HEADER}${JSON.stringify(abi, null, 2)} as const;\n`;
    if (fs.readFileSync(sideBetAbiFile, "utf8") !== next) {
      result.sideBetStale = true;
      if (!checkOnly) {
        fs.writeFileSync(sideBetAbiFile, next);
        result.sideBetWritten = true;
      }
      log(`[update-frontend-abis] ${checkOnly ? "STALE" : "wrote"} Sepolia snapshot side-bet.ts (${abi.length} fragments)`);
    } else {
      log("[update-frontend-abis] Sepolia snapshot side-bet.ts already up to date");
    }
  } else {
    log(`[update-frontend-abis] side-bet.ts left untouched. ${SIDE_BET_REFUSAL}`);
  }

  // ── merged-errors.json (both chains) ───────────────────────────────────────────
  if (!fs.existsSync(mergedErrorsFile)) throw new Error(`missing frontend file: ${mergedErrorsFile}`);
  const merged = JSON.parse(fs.readFileSync(mergedErrorsFile, "utf8"));
  const known = new Set(merged.filter((fragment) => fragment.type === "error").map(signature));
  for (const source of ERROR_SOURCES) {
    for (const fragment of readAbi(path.join(artifactsDir, source))) {
      if (fragment.type !== "error" || known.has(signature(fragment))) continue;
      known.add(signature(fragment));
      result.addedErrors.push({ type: "error", name: fragment.name, inputs: fragment.inputs ?? [] });
    }
  }
  if (result.addedErrors.length > 0) {
    if (!checkOnly) fs.writeFileSync(mergedErrorsFile, `${JSON.stringify([...merged, ...result.addedErrors], null, 2)}\n`);
    log(`[update-frontend-abis] ${checkOnly ? "MISSING from" : "added to"} merged-errors.json: ${result.addedErrors.map(signature).join(", ")}`);
    if (!checkOnly) {
      log("[update-frontend-abis] NOTE: map any new player-facing error in frontend/lib/contract-errors.ts " +
        "(ERROR_TRANSLATION_KEYS) and add its message to messages/*.json.");
    }
  } else {
    log("[update-frontend-abis] merged-errors.json already covers every known contract error");
  }
  return result;
}

function main() {
  const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const frontendDir = process.env.FRONTEND_DIR
    ? path.resolve(repoRoot, process.env.FRONTEND_DIR)
    : path.resolve(repoRoot, "..", "frontend");
  const args = process.argv.slice(2);
  const unknown = args.filter((arg) => !["--check", "--sepolia-snapshot"].includes(arg));
  if (unknown.length > 0) throw new Error(`unknown argument(s): ${unknown.join(" ")}`);
  const checkOnly = args.includes("--check");
  const sepoliaSnapshot = args.includes("--sepolia-snapshot");

  if (!process.env.SKIP_COMPILE && !checkOnly) {
    const compiled = spawnSync("yarn", ["hardhat", "compile"], { cwd: repoRoot, stdio: "inherit", shell: true });
    if (compiled.error) throw compiled.error;
    if (compiled.status !== 0) process.exit(compiled.status ?? 1);
  }
  const result = updateFrontendAbis({ repoRoot, frontendDir, sepoliaSnapshot, checkOnly });
  if (checkOnly && (result.addedErrors.length > 0 || result.sideBetStale)) {
    console.error("[update-frontend-abis] frontend ABIs are stale — run `yarn update:frontend:abis`.");
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(`[update-frontend-abis] ${error.message}`);
    process.exit(1);
  }
}
