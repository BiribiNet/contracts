// Regenerate the small protection ABI without replacing unrelated historical ABIs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { abi } = JSON.parse(fs.readFileSync(path.join(root, 'artifacts/contracts/BankVault4626.sol/BankVault4626.json'), 'utf8'));
const names = new Set(['playerLimits', 'setPlayerLimits', 'selfExclude']);
const fragments = abi.filter(x => names.has(x.name) || x.name?.startsWith('Player') || x.name === 'InvalidPlayerLimits');
fs.writeFileSync(path.join(root, '../frontend/lib/abi/player-protection.ts'), '// Generated by contracts/scripts/export-player-protection.mjs.\nexport const playerProtectionAbi = ' + JSON.stringify(fragments, null, 2) + ' as const;\n');
